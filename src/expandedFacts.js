export function expandedFactQuestions(topic, age, legacyFacts = {}) {
  const band = Number(age) <= 6 ? 0 : Number(age) <= 10 ? 1 : Number(age) <= 13 ? 2 : 3;
  const levels = expandedFacts[topic];
  if (!levels) throw new Error('Unknown learning topic.');
  // Primary and older levels draw from age-relevant questions only; no preschool padding.
  const selected = band === 0 ? levels[0] : band === 1 ? [...levels[0],...levels[1]] : band === 2 ? [...levels[1],...levels[2]] : [...levels[2],...levels[3]];
  const extra = band <= 1 ? (legacyFacts[topic] || []).map(([prompt,answer,options]) => ({prompt,answer,options:[...options],explanation:`The correct answer is ${answer}.`})) : [];
  return [...selected.map(([prompt,answer,wrong1,wrong2,explanation]) => ({prompt,answer,options:[answer,wrong1,wrong2],explanation})),...extra];
}
